DROP DATABASE IF EXISTS empresa;
CREATE DATABASE empresa
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_spanish_ci;

USE empresa;

-- ----------------------------------------------------------------------
-- 2. CREACION DE TABLAS
--    Orden : primero las tablas MAESTRAS (sin dependencias),
--    luego las tablas de DETALLE/TRANSACCIONALES (con FOREIGN KEY),
--    para que las restricciones referenciales se puedan crear sin error.
-- ----------------------------------------------------------------------

-- Tabla MAESTRA: t_departamento
-- ENGINE=InnoDB le indica a MySQL qué motor de almacenamiento usar para esa tabla en particular.
-- En MySQL, cada tabla (no solo cada base de datos) puede tener su propio motor, y ese motor
-- determina cómo se guardan y gestionan físicamente los datos por debajo.
CREATE TABLE t_departamento (
    id             INT AUTO_INCREMENT PRIMARY KEY,
    nombre         VARCHAR(100) NOT NULL,
    ciudad         VARCHAR(100) NOT NULL,
    presupuesto    DECIMAL(12,2) NOT NULL DEFAULT 0,
    fechacreacion  DATE NOT NULL DEFAULT (CURRENT_DATE)
) ENGINE=InnoDB;

-- Tabla MAESTRA: t_producto
CREATE TABLE t_producto (
    id             INT AUTO_INCREMENT PRIMARY KEY,
    nombre         VARCHAR(150) NOT NULL,
    categoria      VARCHAR(60)  NOT NULL,
    precio         DECIMAL(10,2) NOT NULL,
    stock          INT NOT NULL DEFAULT 0,
    fechacreacion  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- Tabla MAESTRA: t_cliente
CREATE TABLE t_cliente (
    id             INT AUTO_INCREMENT PRIMARY KEY,
    nombre         VARCHAR(100) NOT NULL,
    apellido       VARCHAR(100) NOT NULL,
    email          VARCHAR(150) NOT NULL UNIQUE,
    ciudad         VARCHAR(100),
    fecharegistro  DATE NOT NULL DEFAULT (CURRENT_DATE)
) ENGINE=InnoDB;

-- Tabla de DETALLE: t_personal (depende de t_departamento)
CREATE TABLE t_personal (
    id               INT AUTO_INCREMENT PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL,
    apellido         VARCHAR(100) NOT NULL,
    email            VARCHAR(150) NOT NULL UNIQUE,
    ciudad           VARCHAR(100),
    salario          INT NOT NULL,
    departamento_id  INT NOT NULL,
    fecharegistro    DATE NOT NULL DEFAULT (CURRENT_DATE),
    CONSTRAINT fk_personal_departamento
        FOREIGN KEY (departamento_id) REFERENCES t_departamento(id)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

-- Tabla de DETALLE: t_venta (depende de t_cliente y t_producto)
CREATE TABLE t_venta (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    cliente_id    INT NOT NULL,
    producto_id   INT NOT NULL,
    cantidad      INT NOT NULL DEFAULT 1,
    fecha_venta   DATE NOT NULL,
    total         DECIMAL(12,2) NOT NULL,
    CONSTRAINT fk_venta_cliente
        FOREIGN KEY (cliente_id) REFERENCES t_cliente(id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_venta_producto
        FOREIGN KEY (producto_id) REFERENCES t_producto(id)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

-- -------------------------------------------------------------------
-- 2.1 INDICES NO UNICOS ADICIONALES
--     (utiles luego para consultar information_schema.statistics)
-- -------------------------------------------------------------------
CREATE INDEX i_departamento_ciudad ON t_departamento (ciudad);
CREATE INDEX i_producto_categoria  ON t_producto (categoria);
CREATE INDEX i_cliente_ciudad      ON t_cliente (ciudad);
CREATE INDEX i_venta_fecha         ON t_venta (fecha_venta);

